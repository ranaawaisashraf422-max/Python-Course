#Concatination
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(t1+t2)

#Repition
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(t2*3)

#Membership(in)
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print("Awais" in t2)

#Membership (out)
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(20 not in t1)

#Indexing
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(t2[2])

#Slicing
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(t2[0:2:])

#Maximum
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(max(t1))

#Minimun
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(min(t2))

#length
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")
print(len(t2))

#Sum
t1 = (10, 20, 30)
t2 = ("Awais", "Abeeha", "Los Angeles")

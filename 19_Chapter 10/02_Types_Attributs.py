class Employee:
    language = "Punjabi" #Class ATTRIBUTES
    Salary = 1200000     #Class ATTRIBUTES



harry = Employee()  #Object Creation

#Instance Attribute Making
harry.name="Awais"

print(harry.name,harry.language,harry.Salary)

#Rohan Object Creation
rohan = Employee()

#Instance Attribute Making
rohan.name="Rohan Robinson"

print(rohan.name,rohan.language,rohan.Salary)

# Here is name is object Attribute and language and salary are class atributs as they are directly belong to the class